#!/usr/bin/env node
// Generates app/dash-accent.css: every globals.css rule that hardcodes the brand purple, re-emitted with the
// purple swapped for var(--dash-accent) and scoped to html.dash-custom-accent, so a custom dashboard accent
// recolours the dashboard without touching public profile pages.
// Usage: node scripts/gen-dash-accent-css.js

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "app", "globals.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

const PURPLE = /rgba\(\s*124\s*,\s*58\s*,\s*237\s*,\s*([\d.]+)\s*\)|#7c3aed\b|#8b5cf6\b|#a78bfa\b|#6d28d9\b|#c4b5fd\b|#1e40af\b|var\(--accent\)/gi;

function recolor(value) {
  return value.replace(PURPLE, (m, alpha) => {
    if (alpha !== undefined) return `color-mix(in srgb, var(--dash-accent) ${Math.round(parseFloat(alpha) * 100)}%, transparent)`;
    switch (m.toLowerCase()) {
      case "#7c3aed": case "var(--accent)": return "var(--dash-accent)";
      case "#8b5cf6": return "color-mix(in srgb, var(--dash-accent) 85%, #fff)";
      case "#a78bfa": return "color-mix(in srgb, var(--dash-accent) 65%, #fff)";
      case "#c4b5fd": return "color-mix(in srgb, var(--dash-accent) 45%, #fff)";
      case "#6d28d9": return "color-mix(in srgb, var(--dash-accent) 80%, #000)";
      case "#1e40af": return "color-mix(in srgb, var(--dash-accent) 55%, #000)";
      default: return m;
    }
  });
}

function scopeSelector(sel) {
  return sel.split(",").map((s) => {
    s = s.trim();
    if (!s) return s;
    if (/^(html|:root)\b/.test(s)) return s.replace(/^(html|:root)/, "html.dash-custom-accent");
    return `html.dash-custom-accent ${s}`;
  }).join(", ");
}

// Minimal brace-matching parser: returns [{ prelude, body }] for one nesting level.
function parseBlocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) break;
    const prelude = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    out.push({ prelude, body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}

function processBlocks(css) {
  const lines = [];
  for (const { prelude, body } of parseBlocks(css)) {
    if (/^@(keyframes|-webkit-keyframes|font-face|property)/.test(prelude)) continue;
    if (prelude.startsWith("@")) {
      const inner = processBlocks(body);
      if (inner) lines.push(`${prelude} {\n${inner}\n}`);
      continue;
    }
    if (prelude.includes(".profile") || prelude.includes("#profile") || prelude.includes(".badge-")) continue;
    const decls = body.split(";").map((d) => d.trim()).filter((d) => d && /:/.test(d) && PURPLE.test(d.split(":").slice(1).join(":")));
    PURPLE.lastIndex = 0;
    const recolored = decls
      .filter((d) => { const ok = new RegExp(PURPLE.source, "i").test(d.slice(d.indexOf(":") + 1)); return ok; })
      .map((d) => `${d.slice(0, d.indexOf(":") + 1)}${recolor(d.slice(d.indexOf(":") + 1))}`);
    if (recolored.length) lines.push(`${scopeSelector(prelude)} { ${recolored.join("; ")}; }`);
  }
  return lines.join("\n");
}

const header = "/* Generated by scripts/gen-dash-accent-css.js — do not edit by hand. */\nhtml.dash-custom-accent { --accent: var(--dash-accent); }\n";
fs.writeFileSync(path.join(root, "app", "dash-accent.css"), header + processBlocks(src) + "\n");
console.log("wrote app/dash-accent.css");
